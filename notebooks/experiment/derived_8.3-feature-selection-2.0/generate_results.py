def _selection_path_map(path: Path, key: str = "selection_path") -> dict[int, tuple[str, ...]]:
    payload = _read_json(path)
    paths = _candidate_path_features(payload, key)
    result = {}
    for features in paths:
        count = len(features)
        if count in result:
            raise ValueError(f"duplicate feature count in a single path: {path}/{count}")
        result[count] = tuple(features)
    return result


