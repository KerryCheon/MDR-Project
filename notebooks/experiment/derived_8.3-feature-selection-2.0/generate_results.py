def _require_one_row(
    frame: pd.DataFrame,
    filters: Mapping[str, object],
    *,
    source: str,
) -> pd.Series:
    mask = pd.Series(True, index=frame.index)
    for column, value in filters.items():
        if column not in frame.columns:
            raise ValueError(f"missing filter column {column!r} in {source}")
        mask &= frame[column] == value
    rows = frame.loc[mask]
    if len(rows) != 1:
        raise ValueError(f"expected exactly one row in {source} for {dict(filters)}, got {len(rows)}")
    return rows.iloc[0]


