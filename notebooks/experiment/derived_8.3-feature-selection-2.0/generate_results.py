        ("nested_locked_outer", "derived_8.3", ("global",)),
        ("crossed_candidates_locked_outer", "derived_8.0", ("global",)),
        ("crossed_candidates_locked_outer", "derived_8.3", ("global",)),
        ("progressive_crossed_locked_outer", "derived_8.0", ("global",)),
