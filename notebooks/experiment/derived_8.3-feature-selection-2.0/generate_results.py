def _markdown_table(frame: pd.DataFrame) -> str:
    display = frame.copy()
    for column in display.select_dtypes(include="number"):
        display[column] = display[column].map(lambda value: f"{value:.4f}" if isinstance(value, float) else str(value))
    return display.to_markdown(index=False)


def _render_evidence_section(
    title: str,
    source: str,
    frame: pd.DataFrame,
    columns: Iterable[str],
) -> list[str]:
    if frame.empty:
        raise ValueError(f"generated evidence section is empty: {title}")
    selected_columns = list(columns)
    missing = [column for column in selected_columns if column not in frame]
    if missing:
        raise ValueError(f"generated evidence section {title} is missing {missing}")
    return [f"### {title}", "", source, "", _markdown_table(frame[selected_columns]), ""]


