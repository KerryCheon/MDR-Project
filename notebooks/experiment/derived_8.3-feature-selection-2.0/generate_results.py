def validate_station_metric_coverage(
    metrics: pd.DataFrame,
    *,
    coverage: pd.DataFrame,
    artifact_set: str,
    beta: float,
) -> pd.DataFrame:
    """Require every test station for each report model before joining metrics."""
    validate_unique_finite_rows(
        metrics,
        source=f"{artifact_set} station metrics",
        unique_by=("dataset", "model", "beta", "station_id"),
        required_columns=("dataset", "model", "beta", "station_id"),
    )
    validate_unique_finite_rows(
        coverage[["dataset", "station", "test_row_count"]],
        source="station coverage for metric validation",
        unique_by=("dataset", "station"),
        required_columns=("dataset", "station", "test_row_count"),
    )
    selected_parts = []
    for dataset in HISTORICAL_BASELINES:
        expected_stations = set(
            coverage.loc[
                coverage["dataset"].eq(dataset) & coverage["test_row_count"].gt(0),
                "station",
            ].astype(str)
        )
        if not expected_stations:
            raise ValueError(f"test coverage has no observed stations for {dataset}")
        for model in expected_station_metric_models(artifact_set, dataset):
            rows = metrics.loc[
                metrics["dataset"].eq(dataset) & metrics["model"].eq(model) & metrics["beta"].eq(float(beta))
            ].copy()
            actual_stations = set(rows["station_id"].astype(str))
            if actual_stations != expected_stations:
                raise ValueError(
                    f"station metric coverage mismatch for "
                    f"{artifact_set}/{dataset}/{model}/beta={beta}: "
                    f"missing={sorted(expected_stations - actual_stations)}, "
                    f"extra={sorted(actual_stations - expected_stations)}"
                )
            selected_parts.append(rows)
    return pd.concat(selected_parts, ignore_index=True)


def _balanced_station_groups(
    stations: pd.Series,
    n_splits: int,
) -> list[tuple[str, ...]]:
    """Mirror grouped_oof._balanced_station_groups for coverage auditing."""
    station_text = stations.astype(str)
    counts = station_text.value_counts().sort_index()
    if len(counts) < 2:
        raise ValueError("coverage audit requires at least two stations")
    n_groups = min(max(2, int(n_splits)), len(counts))
    groups: list[list[str]] = [[] for _ in range(n_groups)]
    loads = [0 for _ in range(n_groups)]
    ordered = sorted(counts.items(), key=lambda item: (-int(item[1]), str(item[0])))
    for station, count in ordered:
        group_index = min(range(n_groups), key=lambda index: (loads[index], index))
        groups[group_index].append(str(station))
        loads[group_index] += int(count)
    return [tuple(sorted(group)) for group in groups if group]


def compute_outer_fold_coverage(
    *,
    dataset: str,
    train: pd.DataFrame,
    validation: pd.DataFrame,
    saved_folds: Iterable[dict],
    station_groups: Iterable[Iterable[str]] | None = None,
    n_station_folds: int = 4,
    max_validation_years: int | None = None,
) -> pd.DataFrame:
    train = train.copy()
    validation = validation.copy()
    train[STATION_COL] = train[STATION_COL].astype(str)
    validation[STATION_COL] = validation[STATION_COL].astype(str)
    validation[TIME_COL] = pd.to_datetime(validation[TIME_COL], errors="raise")
    groups = (
        [tuple(sorted(map(str, group))) for group in station_groups]
        if station_groups is not None
        else _balanced_station_groups(
            pd.concat(
                [
                    train[STATION_COL],
                    pd.Series(
                        sorted(set(validation[STATION_COL]) - set(train[STATION_COL])),
                        dtype="object",
                    ),
                ],
                ignore_index=True,
            ),
            n_station_folds,
        )
    )
    fold_lookup = {}
    for fold in saved_folds:
        key = (
            int(fold["validation_year"]),
            tuple(sorted(map(str, fold["held_out_stations"]))),
        )
        if key in fold_lookup:
            raise ValueError(f"duplicate saved outer fold: {dataset}/{key}")
        fold_lookup[key] = str(fold["fold_id"])

    validation_years = sorted(validation[TIME_COL].dt.year.unique())
    max_years = len(validation_years) if max_validation_years is None else int(max_validation_years)
    if max_years:
        validation_years = validation_years[-max_years:]
    train_station_counts = train[STATION_COL].value_counts()
    validation_counts = validation.groupby([validation[TIME_COL].dt.year, STATION_COL]).size()
    validation_total_counts = validation[STATION_COL].value_counts()
    rows = []
    for year in validation_years:
        for group_index, held_out in enumerate(groups):
            group_key = (int(year), tuple(held_out))
            saved_fold_id = fold_lookup.get(group_key, "")
            group_count = int(sum(validation_counts.get((int(year), station), 0) for station in held_out))
            for station in held_out:
                station_count = int(validation_counts.get((int(year), station), 0))
                listed = bool(saved_fold_id)
                rows.append(
                    {
                        "dataset": dataset,
                        "validation_year": int(year),
                        "station_group": group_index,
                        "assigned_held_out_station": station,
                        "assigned_station_train_rows": int(train_station_counts.get(station, 0)),
                        "actual_validation_row_count": station_count,
                        "group_validation_row_count": group_count,
                        "saved_fold_id": saved_fold_id,
                        "listed_in_saved_fold": listed,
                        "truly_scored": listed and station_count > 0,
                        "listed_but_not_scored": listed and station_count == 0,
                        "development_station": station in train_station_counts.index,
                        "development_station_never_in_outer_period": bool(
                            station in train_station_counts.index and validation_total_counts.get(station, 0) == 0
                        ),
                    }
                )
    result = pd.DataFrame(rows)
    return validate_unique_finite_rows(
        result,
        source=f"outer fold coverage for {dataset}",
        unique_by=("dataset", "validation_year", "assigned_held_out_station"),
    )


