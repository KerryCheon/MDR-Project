def build_station_diagnostic_selection_table(
    station_errors: pd.DataFrame | None = None,
) -> pd.DataFrame:
    """Select report stations by a declared performance rule, never by name."""
    source = station_errors.copy() if station_errors is not None else build_station_coverage_error_table()
    rows = source.loc[
        source["artifact_arm"].eq("nested")
        & source["dataset"].eq("derived_8.3")
        & source["model"].eq("2.0_global")
        & source["beta"].eq(0.0)
    ].copy()
    validate_unique_finite_rows(
        rows,
        source="station diagnostic selection input",
        unique_by=("station",),
        required_columns=("station", "R2", "RMSE"),
    )
    maximum_rmse = float(rows["RMSE"].max())
    rows["negative_R2"] = rows["R2"].lt(0.0)
    rows["maximum_RMSE"] = np.isclose(rows["RMSE"], maximum_rmse, rtol=1e-12, atol=1e-12)
    rows = rows.loc[rows["negative_R2"] | rows["maximum_RMSE"]].copy()
    rows["selection_reason"] = rows.apply(
        lambda row: (
            "negative_R2_and_maximum_RMSE"
            if row["negative_R2"] and row["maximum_RMSE"]
            else ("negative_R2" if row["negative_R2"] else "maximum_RMSE")
        ),
        axis=1,
    )
    columns = [
        "dataset",
        "artifact_arm",
        "model",
        "beta",
        "station",
        "R2",
        "RMSE",
        "negative_R2",
        "maximum_RMSE",
        "selection_reason",
    ]
    return (
        validate_unique_finite_rows(
            rows[columns],
            source="station diagnostic selection",
            unique_by=("station",),
        )
        .sort_values(["selection_reason", "station"])
        .reset_index(drop=True)
    )


