def compute_pairwise_feature_overlap(
    feature_sets: Mapping[str, Iterable[str]],
    *,
    dataset: str,
) -> pd.DataFrame:
    rows = []
    normalized = {name: set(features) for name, features in feature_sets.items()}
    for name, values in normalized.items():
        if not values:
            raise ValueError(f"empty feature set: {dataset}/{name}")
    for (name_a, set_a), (name_b, set_b) in combinations(normalized.items(), 2):
        intersection = len(set_a & set_b)
        union = len(set_a | set_b)
        rows.append(
            {
                "dataset": dataset,
                "set_a": name_a,
                "set_b": name_b,
                "n_a": len(set_a),
                "n_b": len(set_b),
                "intersection": intersection,
                "union": union,
                "jaccard": intersection / union,
            }
        )
    return pd.DataFrame(rows)


