def _coverage_summary_for_station(
    frame: pd.DataFrame,
    station: str,
) -> dict:
    rows = frame.loc[frame[STATION_COL].astype(str) == station]
    if rows.empty:
        return {
            "row_count": 0,
            "first_date": "",
            "last_date": "",
            "target_mean": None,
            "target_standard_deviation": None,
        }
    dates = pd.to_datetime(rows[TIME_COL], errors="raise")
    values = pd.to_numeric(rows[TARGET], errors="raise").to_numpy(dtype=float)
    if not np.isfinite(values).all():
        raise ValueError(f"non-finite station target for {station}")
    return {
        "row_count": len(rows),
        "first_date": dates.min().date().isoformat(),
        "last_date": dates.max().date().isoformat(),
        "target_mean": float(np.mean(values)),
        "target_standard_deviation": float(np.std(values, ddof=0)),
    }


def build_station_coverage_table(
    split_frames: Mapping[tuple[str, str], pd.DataFrame] | None = None,
) -> pd.DataFrame:
    rows = []
    for dataset in ("derived_8.0", "derived_8.3"):
        frames = {
            split: (
                split_frames[(dataset, split)].copy()
                if split_frames is not None
                else _load_split_columns(dataset, split).copy()
            )
            for split in ("train", "val", "test")
        }
        stations = sorted(set().union(*(set(frame[STATION_COL].astype(str)) for frame in frames.values())))
        for station in stations:
            summaries = {split: _coverage_summary_for_station(frame, station) for split, frame in frames.items()}
            development_dates = [
                summaries[split]["last_date"] for split in ("train", "val") if summaries[split]["last_date"]
            ]
            last_development = max(development_dates) if development_dates else ""
            first_test = summaries["test"]["first_date"]
            gap_days = (
                (pd.Timestamp(first_test) - pd.Timestamp(last_development)).days
                if first_test and last_development
                else None
            )
            row = {
                "dataset": dataset,
                "station": station,
                "last_development_observation": last_development,
                "first_test_observation": first_test,
                "return_gap_days": gap_days,
                "test_target_mean": summaries["test"]["target_mean"],
                "test_target_standard_deviation": summaries["test"]["target_standard_deviation"],
            }
            for split in ("train", "val", "test"):
                row[f"{split}_row_count"] = summaries[split]["row_count"]
                row[f"{split}_first_date"] = summaries[split]["first_date"]
                row[f"{split}_last_date"] = summaries[split]["last_date"]
            rows.append(row)
    result = pd.DataFrame(rows)
    for split in ("train", "val", "test"):
        counts = pd.to_numeric(result[f"{split}_row_count"], errors="raise")
        if (counts < 0).any() or not np.equal(counts, np.floor(counts)).all():
            raise ValueError(f"invalid {split} row count in station coverage table")
    observed_test = result["test_row_count"].gt(0)
    for column in ("test_target_mean", "test_target_standard_deviation"):
        values = pd.to_numeric(result.loc[observed_test, column], errors="coerce")
        if values.isna().any() or not np.isfinite(values.to_numpy(dtype=float)).all():
            raise ValueError(f"missing observed test target summary in station coverage table: {column}")
        if result.loc[~observed_test, column].notna().any():
            raise ValueError(f"unexpected test target summary for absent station: {column}")
    expected_gap = result["last_development_observation"].ne("") & result["first_test_observation"].ne("")
    if result.loc[expected_gap, "return_gap_days"].isna().any():
        raise ValueError("missing return gap for observed development-to-test transition")
    if result.loc[~expected_gap, "return_gap_days"].notna().any():
        raise ValueError("return gap is defined without both development and test observations")
    return (
        validate_unique_finite_rows(
            result,
            source="station coverage table",
            unique_by=("dataset", "station"),
            nullable_numeric_columns=NULLABLE_STATION_COVERAGE_NUMERIC,
        )
        .sort_values(["dataset", "station"])
        .reset_index(drop=True)
    )


