def replace_generated_block(document: str, generated_content: str) -> str:
    """Replace only the bytes between the unique generated-block markers."""
    begin_count = document.count(BEGIN_ERROR_ANALYSIS)
    end_count = document.count(END_ERROR_ANALYSIS)
    if begin_count != 1 or end_count != 1:
        raise ValueError(
            "CONTINUATION.md must contain exactly one generated error-analysis "
            f"marker pair; found begin={begin_count}, end={end_count}"
        )
    begin = document.index(BEGIN_ERROR_ANALYSIS)
    end = document.index(END_ERROR_ANALYSIS)
    if end < begin:
        raise ValueError("generated error-analysis markers are reversed")
    if BEGIN_ERROR_ANALYSIS in generated_content or END_ERROR_ANALYSIS in generated_content:
        raise ValueError("generated content must not contain block markers")
    content_start = begin + len(BEGIN_ERROR_ANALYSIS)
    return document[:content_start] + "\n" + generated_content.strip("\n") + "\n" + document[end:]


