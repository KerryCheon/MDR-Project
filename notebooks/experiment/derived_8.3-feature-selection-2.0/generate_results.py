def verify_live_split_hashes(
    expected: Mapping[str, Mapping[str, str]],
) -> dict[str, dict[str, str]]:
    """Reject live split files that differ from any completed report source."""
    verified: dict[str, dict[str, str]] = {dataset: {} for dataset in DATASETS}
    for dataset in DATASETS:
        for split in SPLITS:
            path = PROJECT_ROOT / "data/splits" / dataset / f"{split}.csv"
            actual = sha256_file(path)
            expected_hash = validate_sha256(
                expected.get(dataset, {}).get(split),
                source=f"expected report provenance for {dataset}/{split}",
            )
            if actual != expected_hash:
                raise ValueError(
                    f"live split hash mismatch for {dataset}/{split}: "
                    f"expected={expected_hash}, actual={actual}, path={path}"
                )
            verified[dataset][split] = actual
    return verified


