def _read_json(path: Path) -> dict:
    if not path.is_file():
        raise FileNotFoundError(path)
    try:
        with open(path, encoding="utf-8") as stream:
            payload = json.load(stream)
    except json.JSONDecodeError as error:
        raise ValueError(f"invalid JSON source: {path}") from error
    if not isinstance(payload, dict):
        raise ValueError(f"expected a JSON object in {path}")
    return payload


def validate_unique_finite_rows(
    frame: pd.DataFrame,
    *,
    source: str | Path,
    unique_by: Iterable[str] | None = None,
    required_columns: Iterable[str] = (),
    nullable_numeric_columns: Iterable[str] = (),
) -> pd.DataFrame:
    """Reject missing, duplicate, or non-finite tabular source rows."""
    required = list(required_columns)
    missing = [column for column in required if column not in frame.columns]
    if missing:
        raise ValueError(f"missing columns in {source}: {missing}")
    if frame.empty:
        raise ValueError(f"missing source rows in {source}")
    nullable = set(nullable_numeric_columns)
    missing_nullable = sorted(nullable - set(frame.columns))
    if missing_nullable:
        raise ValueError(f"missing nullable numeric columns in {source}: {missing_nullable}")
    numeric = frame.select_dtypes(include="number")
    strict_numeric = numeric.drop(columns=list(nullable & set(numeric.columns)), errors="ignore")
    if not np.isfinite(strict_numeric.to_numpy(dtype=float)).all():
        raise ValueError(f"non-finite metric in {source}")
    for column in nullable:
        converted = pd.to_numeric(frame[column], errors="coerce")
        if (frame[column].notna() & converted.isna()).any():
            raise ValueError(f"non-numeric metric in {source}: {column}")
        observed = converted.dropna().to_numpy(dtype=float)
        if not np.isfinite(observed).all():
            raise ValueError(f"non-finite metric in {source}: {column}")
    keys = list(unique_by or [])
    if keys:
        missing_keys = [column for column in keys if column not in frame.columns]
        if missing_keys:
            raise ValueError(f"missing uniqueness columns in {source}: {missing_keys}")
        duplicates = frame.duplicated(keys, keep=False)
    else:
        duplicates = frame.duplicated(keep=False)
    if duplicates.any():
        sample = frame.loc[duplicates, keys or list(frame.columns)].head(5)
        raise ValueError(f"duplicate source rows in {source}: {sample.to_dict('records')}")
    return frame


def _read_csv(
    path: Path,
    *,
    unique_by: Iterable[str] | None = None,
    required_columns: Iterable[str] = (),
) -> pd.DataFrame:
    if not path.is_file():
        raise FileNotFoundError(path)
    frame = pd.read_csv(path)
    return validate_unique_finite_rows(
        frame,
        source=path,
        unique_by=unique_by,
        required_columns=required_columns,
    )


