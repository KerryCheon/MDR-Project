def build_report_manifest(
    evidence_paths: Iterable[Path],
    *,
    split_hashes: Mapping[str, Mapping[str, str]],
    created: str | None = None,
) -> dict:
    markdown_outputs = {}
    for path in (RESULTS_PATH, CONTINUATION_PATH):
        if not path.is_file():
            raise FileNotFoundError(path)
        markdown_outputs[path.name] = {
            "path": str(path.relative_to(EXP_DIR)),
            "sha256": sha256_file(path),
        }
    evidence = []
    for path in evidence_paths:
        if not path.is_file():
            raise FileNotFoundError(path)
        matches = [
            (key, builder)
            for key, (filename, builder) in EVIDENCE_SPECS.items()
            if filename == path.name
        ]
        if len(matches) != 1:
            raise ValueError(f"unregistered or duplicate evidence path: {path}")
        key, builder = matches[0]
        evidence.append(
            {
                "key": key,
                "builder": builder,
                "path": str(path.relative_to(EXP_DIR)),
                "sha256": sha256_file(path),
            }
        )
    split_inputs = []
    for dataset in DATASETS:
        for split in SPLITS:
            path = PROJECT_ROOT / "data/splits" / dataset / f"{split}.csv"
            digest = validate_sha256(
                split_hashes.get(dataset, {}).get(split),
                source=f"report manifest split hash for {dataset}/{split}",
            )
            if sha256_file(path) != digest:
                raise ValueError(f"split changed before report manifest creation: {path}")
            split_inputs.append(
                {
                    "dataset": dataset,
                    "split": split,
                    "path": str(path.relative_to(PROJECT_ROOT)),
                    "sha256": digest,
                }
            )
    generator_paths = (
        Path(__file__).resolve(),
        EXP_DIR / "data_loading.py",
        EXP_DIR / "split_provenance.py",
    )
    feature_source_path, _ = resolve_source_path(
        PROJECT_ROOT,
        V0_FEATURE_SOURCE,
    )
    return {
        "created": created or datetime.now(timezone.utc).isoformat(),
        "build": {
            "command": REPORT_COMMAND,
            "check_command": f"{REPORT_COMMAND} --check",
            "generators": [
                {
                    "path": str(path.relative_to(EXP_DIR)),
                    "sha256": sha256_file(path),
                }
                for path in generator_paths
            ],
        },
        "feature_sources": [
            {
                "source": V0_FEATURE_SOURCE,
                "path": str(feature_source_path.relative_to(PROJECT_ROOT)),
                "sha256": source_sha256(PROJECT_ROOT, V0_FEATURE_SOURCE),
            }
        ],
        "split_inputs": split_inputs,
        "markdown_outputs": markdown_outputs,
        "generated_evidence": evidence,
    }


def _validate_evidence_registry(tables: Mapping[str, pd.DataFrame]) -> None:
    missing_tables = set(EVIDENCE_SPECS) - set(tables)
    extra_tables = set(tables) - set(EVIDENCE_SPECS)
    if missing_tables or extra_tables:
        raise ValueError(
            "evidence table registry mismatch: "
            f"missing={missing_tables}, extra={extra_tables}"
        )


def report_completion_files() -> list[str]:
    """Return every output, generator, and live split guarded by completion."""
    paths = [
        REPORT_DIR / "report_manifest.json",
        *(REPORT_DIR / filename for filename in EVIDENCE_FILES.values()),
        RESULTS_PATH,
        CONTINUATION_PATH,
        Path(__file__).resolve(),
        EXP_DIR / "data_loading.py",
        EXP_DIR / "split_provenance.py",
        resolve_source_path(PROJECT_ROOT, V0_FEATURE_SOURCE)[0],
        *(
            PROJECT_ROOT / "data/splits" / dataset / f"{split}.csv"
            for dataset in DATASETS
            for split in SPLITS
        ),
    ]
    return [Path(os.path.relpath(path, REPORT_DIR)).as_posix() for path in paths]


def _expected_markdown(
    bundle: Mapping[str, object],
    *,
    continuation_document: str | None = None,
) -> tuple[str, str]:
    tables = bundle["evidence"]
    _validate_evidence_registry(tables)
    continuation = (
        CONTINUATION_PATH.read_text(encoding="utf-8")
        if continuation_document is None
        else continuation_document
    )
    return (
        render_results_markdown(bundle),
        replace_generated_block(continuation, render_error_analysis_block(tables)),
    )


def _validate_report_manifest(
    manifest: Mapping[str, object],
    *,
    split_hashes: Mapping[str, Mapping[str, str]],
) -> None:
    build = manifest.get("build")
    if not isinstance(build, Mapping):
        raise ValueError("report manifest is missing build metadata")
    if build.get("command") != REPORT_COMMAND or build.get("check_command") != (
        f"{REPORT_COMMAND} --check"
    ):
        raise ValueError("report manifest command metadata is stale")
    expected_generators = {
        str(path.relative_to(EXP_DIR)): sha256_file(path)
        for path in (
            Path(__file__).resolve(),
            EXP_DIR / "data_loading.py",
            EXP_DIR / "split_provenance.py",
        )
    }
    recorded_generators = {
        str(entry.get("path")): str(entry.get("sha256"))
        for entry in build.get("generators", [])
        if isinstance(entry, Mapping)
    }
    if recorded_generators != expected_generators:
        raise ValueError("report manifest generator hashes are stale")

    feature_source_path, _ = resolve_source_path(
        PROJECT_ROOT,
        V0_FEATURE_SOURCE,
    )
    expected_feature_sources = {
        V0_FEATURE_SOURCE: (
            str(feature_source_path.relative_to(PROJECT_ROOT)),
            source_sha256(PROJECT_ROOT, V0_FEATURE_SOURCE),
        )
    }
    recorded_feature_sources = {
        str(entry.get("source")): (
            str(entry.get("path")),
            str(entry.get("sha256")),
        )
        for entry in manifest.get("feature_sources", [])
        if isinstance(entry, Mapping)
    }
    if recorded_feature_sources != expected_feature_sources:
        raise ValueError("report manifest feature sources are stale")

    expected_splits = {
        (dataset, split): (
            str(
                (PROJECT_ROOT / "data/splits" / dataset / f"{split}.csv").relative_to(
                    PROJECT_ROOT
                )
            ),
            split_hashes[dataset][split],
        )
        for dataset in DATASETS
        for split in SPLITS
    }
    recorded_splits = {
        (str(entry.get("dataset")), str(entry.get("split"))): (
            str(entry.get("path")),
            str(entry.get("sha256")),
        )
        for entry in manifest.get("split_inputs", [])
        if isinstance(entry, Mapping)
    }
    if recorded_splits != expected_splits:
        raise ValueError("report manifest split inputs are stale")

    expected_markdown = {path.name: path for path in (RESULTS_PATH, CONTINUATION_PATH)}
    recorded_markdown = manifest.get("markdown_outputs")
    if not isinstance(recorded_markdown, Mapping) or set(recorded_markdown) != set(
        expected_markdown
    ):
        raise ValueError("report manifest Markdown outputs are incomplete")
    for name, path in expected_markdown.items():
        entry = recorded_markdown[name]
        if not isinstance(entry, Mapping):
            raise ValueError(f"invalid report manifest Markdown entry: {name}")
        if entry.get("path") != str(path.relative_to(EXP_DIR)) or entry.get(
            "sha256"
        ) != sha256_file(path):
            raise ValueError(f"stale report manifest Markdown hash: {name}")

    expected_evidence = {
        key: (builder, str((REPORT_DIR / filename).relative_to(EXP_DIR)))
        for key, (filename, builder) in EVIDENCE_SPECS.items()
    }
    recorded_evidence = {}
    for entry in manifest.get("generated_evidence", []):
        if not isinstance(entry, Mapping):
            raise ValueError("invalid report manifest evidence entry")
        key = str(entry.get("key"))
        if key in recorded_evidence:
            raise ValueError(f"duplicate report manifest evidence key: {key}")
        recorded_evidence[key] = entry
    if set(recorded_evidence) != set(expected_evidence):
        raise ValueError("report manifest evidence registry is incomplete")
    for key, (builder, relative_path) in expected_evidence.items():
        entry = recorded_evidence[key]
        path = EXP_DIR / relative_path
        if (
            entry.get("builder") != builder
            or entry.get("path") != relative_path
            or entry.get("sha256") != sha256_file(path)
        ):
            raise ValueError(f"stale report manifest evidence entry: {key}")


def check_report_outputs(bundle: Mapping[str, object]) -> None:
    """Rebuild expected bytes in memory and reject stale generated outputs."""
    tables = bundle["evidence"]
    _validate_evidence_registry(tables)
    expected_results, expected_continuation = _expected_markdown(bundle)
    expected_text = {
        RESULTS_PATH: expected_results,
        CONTINUATION_PATH: expected_continuation,
    }
    for path, expected in expected_text.items():
        if not path.is_file() or path.read_text(encoding="utf-8") != expected:
            raise ValueError(f"stale generated Markdown output: {path}")
    for key, (filename, _) in EVIDENCE_SPECS.items():
        path = REPORT_DIR / filename
        expected = tables[key].to_csv(index=False).encode("utf-8")
        if not path.is_file() or path.read_bytes() != expected:
            raise ValueError(f"stale generated evidence output: {path}")
    manifest_path = REPORT_DIR / "report_manifest.json"
    manifest = _read_json(manifest_path)
    _validate_report_manifest(manifest, split_hashes=bundle["split_hashes"])
    if not artifact_is_complete(REPORT_DIR, report_completion_files()):
        raise ValueError("report completion marker is missing, incomplete, or stale")
    verify_live_split_hashes(bundle["split_hashes"])


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Recompute all report outputs and fail if tracked outputs are stale.",
    )
    args = parser.parse_args(argv)
    if not args.check:
        REPORT_DIR.mkdir(parents=True, exist_ok=True)
        invalidate_completion(REPORT_DIR)

    bundle = build_report_bundle()
    tables = bundle["evidence"]
    _validate_evidence_registry(tables)
    if args.check:
        check_report_outputs(bundle)
        print("Report outputs are reproducible and current.")
        return

    results_markdown, continuation_markdown = _expected_markdown(bundle)
    verify_live_split_hashes(bundle["split_hashes"])
    invalidate_completion(REPORT_DIR)
    evidence_paths = []
    for key, (filename, _) in EVIDENCE_SPECS.items():
        path = REPORT_DIR / filename
        atomic_write_csv(tables[key], path)
        evidence_paths.append(path)

    atomic_write_text(RESULTS_PATH, results_markdown)
    atomic_write_text(CONTINUATION_PATH, continuation_markdown)
    verify_live_split_hashes(bundle["split_hashes"])
    manifest = build_report_manifest(
        evidence_paths,
        split_hashes=bundle["split_hashes"],
    )
    atomic_write_json(REPORT_DIR / "report_manifest.json", manifest)
    verify_live_split_hashes(bundle["split_hashes"])
    write_completion_marker(
        REPORT_DIR,
        report_completion_files(),
    )
    check_report_outputs(bundle)


if __name__ == "__main__":
    main()
