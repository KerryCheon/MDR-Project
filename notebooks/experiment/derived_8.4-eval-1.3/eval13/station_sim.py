@dataclass
class StationFeatures:
    """Curated per-station feature matrices (index = station_id)."""

    static: pd.DataFrame          # 29 static features (geo + bioclim + soil)
    dynamic: pd.DataFrame         # 10 observed-climatology features
    combined: pd.DataFrame        # static + dynamic (39 features)
    landcover: pd.Series          # land-cover label per station (annotation only)


def build_station_features(project_root: Path, config: dict[str, Any]) -> StationFeatures:
    """Build the per-station feature matrices from the split CSVs.

    Static features come from ``station_static_features.csv`` (co-located with the
    split files); observed climatology is aggregated from the train+val splits, so
    everything is reproducible from tracked data.
    """
    split_path = Path(config["data"]["splits"]["train"])
    split_dir = project_root / split_path.parent
    static_path = split_dir / "station_static_features.csv"
    if not static_path.exists():
        raise FileNotFoundError(f"Missing station static features: {static_path}")

    static = pd.read_csv(static_path).set_index("station_id")
    missing = [c for c in STATIC_FEATURES if c not in static.columns]
    if missing:
        raise ValueError(f"Static features missing from CSV: {missing}")
    landcover = static["landcover_label"].reindex(static.index)
    static = static[STATIC_FEATURES]

    frames = [
        pd.read_csv(project_root / Path(config["data"]["splits"][name]))
        for name in ("train", "val")
    ]
    trainval = pd.concat(frames, ignore_index=True)
    # Aggregate each source variable with mean and std, then flatten the
    # MultiIndex columns to the DYNAMIC_SPEC names (e.g. mean_precip_mm).
    srcs = list(dict.fromkeys(src for src, _how in DYNAMIC_SPEC.values()))
    dynamic = trainval.groupby("station_id").agg({s: ["mean", "std"] for s in srcs})
    dynamic.columns = [f"{how}_{src}" for src, how in dynamic.columns]
    dynamic = dynamic[list(DYNAMIC_SPEC)]
    dynamic = dynamic.reindex(static.index)  # align to the 7 static-feature stations

    # Sanity: no station should be missing observed climatology.
    if dynamic[DYNAMIC_FEATURES].isna().any().any():
        raise ValueError("Observed climatology contains NaN (station with no train/val rows?)")

    FEATURE_GROUPS["observed climatology"] = DYNAMIC_FEATURES
    return StationFeatures(
        static=static,
        dynamic=dynamic[DYNAMIC_FEATURES],
        combined=static.join(dynamic[DYNAMIC_FEATURES]),
        landcover=landcover,
    )


def station_profile_table(feats: StationFeatures, extra: dict[str, pd.Series] | None = None) -> pd.DataFrame:
    """Compact per-station profile for printing (key descriptors + optional extras).

    ``extra`` maps a column name to a Series indexed by station_id (e.g. difficulty).
    """
    profile_cols = [
        "latitude", "longitude", "J_elev_m", "J_slope_deg",
        "J_bio_bio01", "J_bio_bio12",  # mean annual temp (deg C*10), annual precip (mm)
        "J_sand_wfrac_b0", "J_clay_wfrac_b0",
        "mean_precip_mm", "mean_LST_modis", "mean_F_NDVI", "mean_soil_moisture_5cm",
    ]
    profile = feats.combined[profile_cols].round(2)
    profile.insert(0, "landcover", feats.landcover.reindex(profile.index).values)
    for name, series in (extra or {}).items():
        profile[name] = series.reindex(profile.index).round(3).values
    return profile


# ---------------------------------------------------------------------------
# Standardization, distance, clustering
# ---------------------------------------------------------------------------


def standardize(df: pd.DataFrame) -> pd.DataFrame:
    """z-score each column across stations; zero-std columns become all zeros."""
    out = df.copy()
    for col in out.columns:
        std = out[col].std(ddof=0)
        if std > 1e-12:
            out[col] = (out[col] - out[col].mean()) / std
        else:
            out[col] = 0.0
    return out


def pairwise_distance(df_std: pd.DataFrame) -> pd.DataFrame:
    """Euclidean distance matrix (index/columns = station_id) on standardized features."""
    dist = euclidean_distances(df_std.to_numpy())
    return pd.DataFrame(dist, index=df_std.index, columns=df_std.index)


def similarity_matrix(dist: pd.DataFrame) -> pd.DataFrame:
    """Similarity = 1 - distance / max(distance) (0..1, 1 = identical)."""
    dmax = dist.to_numpy().max()
    return 1.0 - dist / dmax


def ward_linkage(df_std: pd.DataFrame) -> np.ndarray:
    """Ward hierarchical linkage matrix (scipy linkage format)."""
    return linkage(df_std.to_numpy(), method="ward")


def leaf_order(Z: np.ndarray, labels: list[str]) -> list[str]:
    """Dendrogram leaf order (station labels) for reordering heatmaps."""
    leaves = dendrogram(Z, no_plot=True)["leaves"]
    return [labels[i] for i in leaves]


def cluster_labels(Z: np.ndarray, k: int, labels: list[str]) -> pd.Series:
    """Flat cluster assignments (k clusters) from the linkage matrix."""
    return pd.Series(
        fcluster(Z, t=k, criterion="maxclust"),
        index=labels,
        name=f"cluster_k{k}",
    )


def pca_projection(df_std: pd.DataFrame, n_components: int = 2) -> tuple[pd.DataFrame, np.ndarray, pd.DataFrame]:
    """PCA scores (stations x PCs), explained-variance ratios, and loadings (PCs x features)."""
    pca = PCA(n_components=n_components)
    scores = pca.fit_transform(df_std.to_numpy())
    scores_df = pd.DataFrame(
        scores,
        index=df_std.index,
        columns=[f"PC{i + 1}" for i in range(n_components)],
    )
    loadings = pd.DataFrame(
        pca.components_,
        index=[f"PC{i + 1}" for i in range(n_components)],
        columns=df_std.columns,
    )
    return scores_df, pca.explained_variance_ratio_, loadings


# ---------------------------------------------------------------------------
# Isolation scores and hypothesis test
# ---------------------------------------------------------------------------


def isolation_scores(df_std: pd.DataFrame) -> pd.DataFrame:
    """Per-station isolation metrics on standardized features.

    - ``nn_dist``: distance to the closest *other* station (1-NN; a "twin" is near).
    - ``mean_dist``: mean distance to all other stations (general "standing out").
    - ``centroid_dist``: distance to the 7-station centroid (extremeness).
    """
    dist = pairwise_distance(df_std).to_numpy()
    n = len(df_std)
    nn = np.full(n, np.nan)
    mean_d = np.full(n, np.nan)
    for i in range(n):
        others = np.delete(dist[i], i)
        nn[i] = others.min()
        mean_d[i] = others.mean()
    centroid = df_std.to_numpy().mean(axis=0)
    cent_d = np.linalg.norm(df_std.to_numpy() - centroid, axis=1)
    return pd.DataFrame(
        {"nn_dist": nn, "mean_dist": mean_d, "centroid_dist": cent_d},
        index=df_std.index,
    )


def load_difficulty(exp_dir: Path) -> pd.DataFrame:
    """Per-station LOSO difficulty (indexed by station_id).

    ``median_r2`` / ``mean_r2`` aggregate over all 56 configurations
    (``loso_station_summary.csv``); ``winner_r2`` is the per-station R2 of the
    best spatial generalizer — the eval-1.3 ``Clustering_Backbone54_k2`` winner
    (the two-regime model developed from the single-regime 54-feature global
    model; eval-1.1's ``Clustering_V0_Full_k2`` winner as fallback) — from
    ``loso_per_config_station.csv``.
    """
    station_summary = pd.read_csv(exp_dir / "loso_station_summary.csv")
    pcs = pd.read_csv(exp_dir / "loso_per_config_station.csv")
    config_summary = pd.read_csv(exp_dir / "loso_config_summary.csv")

    winners = config_summary.loc[config_summary["is_winner"], "config_id"].tolist()
    if not winners:
        raise ValueError("No winning configuration found in loso_config_summary.csv")
    winner_id = next(
        (c for c in winners if c.startswith("Clustering_Backbone54_k2")),
        next((c for c in winners if c.startswith("Clustering_V0_Full_k2")), winners[0]),
    )
    win_r2 = pcs.loc[pcs["config_id"] == winner_id].set_index("station")["r2"]

    out = station_summary[["station", "median_r2", "mean_r2"]].copy()
    out["winner_r2"] = out["station"].map(win_r2)
    out["winner_config"] = winner_id
    return out.set_index("station")


def spearman_table(isolation: pd.DataFrame, difficulty: pd.DataFrame) -> pd.DataFrame:
    """Spearman rank correlations isolation-metric x difficulty-metric.

    Both frames are indexed by station_id. ``rho > 0`` with ``median_r2`` means
    *more isolated stations are easier* (contra the hypothesis); ``rho < 0`` means
    more isolated stations are harder (hypothesized direction).
    """
    rows = []
    diff_aligned = difficulty.reindex(isolation.index)  # align on station_id
    for iso_col in isolation.columns:
        for diff_col in ["median_r2", "mean_r2", "winner_r2"]:
            if diff_col not in diff_aligned.columns:
                continue
            x = isolation[iso_col].to_numpy()
            y = diff_aligned[diff_col].to_numpy()
            rho, p = spearmanr(x, y)
            rows.append({
                "isolation_metric": iso_col,
                "difficulty_metric": diff_col,
                "spearman_rho": round(float(rho), 3),
                "p_value": round(float(p), 3),
                "n": int(len(x)),
            })
    return pd.DataFrame(rows)


# ---------------------------------------------------------------------------
# Figures (saved to out_dir; generated by the results notebook)
# ---------------------------------------------------------------------------

DIFFICULTY_TIERS: list[tuple[str, float, str]] = [
    ("easy (median R2 >= 0.60)", 0.60, "#2ca02c"),
    ("mid (0.45 <= median R2 < 0.60)", 0.45, "#ff7f0e"),
    ("hard (median R2 < 0.45)", -np.inf, "#d62728"),
]


def _tier_color(median_r2: float) -> str:
    for _, threshold, color in DIFFICULTY_TIERS:
        if median_r2 >= threshold:
            return color
    return "#d62728"


def plot_similarity_heatmap(
    sim: pd.DataFrame,
    order: list[str],
    out_dir: Path,
    title_suffix: str = "",
) -> Path:
    """Pairwise station similarity heatmap, rows/cols in dendrogram order."""
    sim = sim.loc[order, order]
    fig, ax = plt.subplots(figsize=(8, 7))
    sns.heatmap(
        sim, annot=True, fmt=".2f", cmap="YlGnBu", vmin=0.0, vmax=1.0,
        linewidths=0.5, ax=ax,
        cbar_kws={"label": "similarity (1 - d/dmax)"},
    )
    ax.set_title(f"Station similarity — standardized static + observed features{title_suffix}",
                 fontsize=12, weight="bold")
    ax.set_xticklabels(ax.get_xticklabels(), rotation=30, ha="right")
    ax.set_yticklabels(ax.get_yticklabels(), rotation=0)
    plt.tight_layout()
    out_path = out_dir / "station_similarity_heatmap.png"
    plt.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close()
    return out_path


def plot_dendrogram(
    Z: np.ndarray,
    labels: list[str],
    difficulty: pd.DataFrame,
    out_dir: Path,
) -> Path:
    """Ward dendrogram with leaf labels colored by difficulty tier + median R2."""
    tier_colors = {s: _tier_color(difficulty.loc[s, "median_r2"]) for s in labels}
    fig, ax = plt.subplots(figsize=(9, 5))
    dendrogram(
        Z, labels=labels, ax=ax, leaf_rotation=0,
        leaf_font_size=9, color_threshold=0,
    )
    for lab in ax.get_xticklabels():
        s = lab.get_text()
        r2 = difficulty.loc[s, "median_r2"]
        lab.set_color(tier_colors.get(s, "k"))
        lab.set_text(f"{s}\nR²={r2:.2f}")
    ax.set_ylabel("Ward linkage distance")
    ax.set_title("Hierarchical clustering of stations (leaf color = LOSO difficulty tier)", fontsize=12, weight="bold")
    handles = [
        plt.Line2D([0], [0], marker="o", color="w", markerfacecolor=c, markersize=8, label=lbl)
        for lbl, _, c in DIFFICULTY_TIERS
    ]
    ax.legend(handles=handles, loc="upper left", fontsize=8, title="Difficulty tier")
    plt.tight_layout()
    out_path = out_dir / "station_dendrogram.png"
    plt.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close()
    return out_path


def plot_pca_scatter(
    scores: pd.DataFrame,
    explained: np.ndarray,
    loadings: pd.DataFrame,
    difficulty: pd.DataFrame,
    out_dir: Path,
    n_arrows: int = 6,
) -> Path:
    """PCA scatter of stations colored by median LOSO R2, with top feature loadings."""
    fig, ax = plt.subplots(figsize=(9, 7))
    med = difficulty.loc[scores.index, "median_r2"]
    sc = ax.scatter(
        scores["PC1"], scores["PC2"], c=med, cmap="RdYlGn",
        vmin=0.3, vmax=0.8, s=180, edgecolors="k", linewidths=0.8, zorder=3,
    )
    for s in scores.index:
        ax.annotate(
            s.replace("_WA", "").replace("_", " "),  # shorter labels
            (scores.loc[s, "PC1"], scores.loc[s, "PC2"]),
            xytext=(6, 6), textcoords="offset points", fontsize=9,
        )
    cbar = plt.colorbar(sc, ax=ax)
    cbar.set_label("median LOSO R²")
    ax.axhline(0, color="grey", lw=0.6, ls="--")
    ax.axvline(0, color="grey", lw=0.6, ls="--")

    # Top feature loadings as arrows from the origin.
    norm = np.linalg.norm(loadings.to_numpy(), axis=1)
    top = np.argsort(norm)[::-1][:n_arrows]
    scale = 0.9 * max(np.abs(scores["PC1"]).max(), np.abs(scores["PC2"]).max())
    for i in top:
        x, y = loadings.iloc[:, i].to_numpy() * scale
        ax.annotate(
            "", xy=(x, y), xytext=(0, 0),
            arrowprops=dict(arrowstyle="->", color="#555555", lw=1.1),
        )
        ax.text(x * 1.08, y * 1.08, short_name(loadings.columns[i]), fontsize=8, color="#444444")

    ax.set_xlabel(f"PC1 ({explained[0] * 100:.1f}% variance)")
    ax.set_ylabel(f"PC2 ({explained[1] * 100:.1f}% variance)")
    ax.set_title("Station embedding (PCA on standardized features)\ncolor = median LOSO R², arrows = top feature loadings",
                 fontsize=12, weight="bold")
    plt.tight_layout()
    out_path = out_dir / "station_pca_scatter.png"
    plt.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close()
    return out_path


def plot_isolation_vs_difficulty(
    isolation: pd.DataFrame,
    difficulty: pd.DataFrame,
    out_dir: Path,
) -> Path:
    """2x2 scatter: isolation metric (1-NN / mean dist) x difficulty (median / winner R2)."""
    fig, axes = plt.subplots(2, 2, figsize=(12, 10))
    iso_metrics = [("nn_dist", "1-NN distance (closest other station)"),
                   ("mean_dist", "mean distance to other stations")]
    diff_metrics = [("median_r2", "median LOSO R² (47 configs)"),
                    ("winner_r2", "winner-config LOSO R²")]
    difficulty = difficulty.reindex(isolation.index)  # align on station_id
    for row, (iso_col, iso_lbl) in enumerate(iso_metrics):
        for col, (diff_col, diff_lbl) in enumerate(diff_metrics):
            ax = axes[row][col]
            x = isolation[iso_col]
            y = difficulty[diff_col]
            ax.scatter(x, y, s=90, edgecolors="k", linewidths=0.7, zorder=3)
            for s in isolation.index:
                ax.annotate(s.replace("_WA", "").replace("_", " "), (x[s], y[s]),
                            xytext=(5, 5), textcoords="offset points", fontsize=8)
            rho, p = spearmanr(x, y)
            ax.set_xlabel(iso_lbl, fontsize=10)
            ax.set_ylabel(diff_lbl, fontsize=10)
            ax.set_title(f"ρ = {rho:+.2f} (p = {p:.2f})", fontsize=11)
            ax.grid(True, ls="--", alpha=0.3)
    fig.suptitle("Isolation vs. spatial-generalization difficulty — hypothesis test",
                 fontsize=13, weight="bold")
    plt.tight_layout()
    out_path = out_dir / "station_isolation_vs_difficulty.png"
    plt.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close()
    return out_path


def plot_feature_heatmap(
    df_std: pd.DataFrame,
    order: list[str],
    out_dir: Path,
) -> Path:
    """Standardized feature matrix (stations x features) in group order, dendrogram row order.

    Highlights which features make the hard stations extreme.
    """
    groups = FEATURE_GROUPS
    cols = [c for group in groups.values() for c in group]
    df = df_std.loc[order, cols]
    fig, ax = plt.subplots(figsize=(15, 4.5))
    sns.heatmap(
        df, cmap="coolwarm", center=0.0, vmin=-2.5, vmax=2.5,
        linewidths=0.5, ax=ax, cbar_kws={"label": "z-score"},
    )
    # Group separators + labels.
    pos = 0
    for name, feats in groups.items():
        if not feats:
            continue
        pos += len(feats)
        ax.axvline(pos, color="black", lw=1.2)
    ticks = [len(feats) / 2 for feats in groups.values() if feats]
    names = [n for n, f in groups.items() if f]
    ax2 = ax.twiny()
    ax2.set_xlim(ax.get_xlim())
    ax2.set_xticks(ticks)
    ax2.set_xticklabels(names, rotation=0, fontsize=8)
    ax2.tick_params(top=False)
    ax.set_xticklabels([short_name(c) for c in df.columns], rotation=90, fontsize=7)
    ax.set_yticklabels([s.replace("_WA", "") for s in df.index], rotation=0, fontsize=9)
    ax.set_title("Station × feature z-scores (rows in dendrogram order; group boundaries marked)",
                 fontsize=12, weight="bold")
    plt.tight_layout()
    out_path = out_dir / "station_features_heatmap.png"
    plt.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close()
    return out_path
