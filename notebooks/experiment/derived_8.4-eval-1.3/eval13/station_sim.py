"""Station-level similarity, clustering, and hypothesis testing for derived_8.4-eval-1.3.

Tests the spatial-generalization hypothesis behind the LOSO experiment:

    * a station generalizes well spatially when the training set contains another
      station with *similar climate and geography* ("a twin"), and
    * a station generalizes poorly when it *stands out* from the other stations.

The analysis is purely descriptive + correlational over the 7 WA stations of the
`derived_8.4` split (n = 7 — correlations are illustrative, not conclusive):

1. Build per-station feature vectors from two reproducible sources:
   - *static* geography/climate/soil features from
     ``data/splits/derived_8.4/station_static_features.csv`` (WorldClim BioClim
     BIO1-19, elevation, slope, aspect sin/cos, lat/lon, surface/deep sand+clay
     fractions), and
   - *observed climatology* — per-station mean/std of key dynamic variables
     (precip, LST, NDVI, SMAP, soil moisture) computed over the train+val splits.
2. z-score standardize, cluster (Ward hierarchical linkage + PCA projection), and
   compute per-station *isolation* scores (1-NN distance, mean distance to the
   other 6 stations, distance to the centroid).
3. Correlate isolation with two LOSO difficulty measures: the median R2 over all
   56 configurations (`loso_station_summary.csv`) and the per-station R2 of the
   best spatial generalizer — the `Clustering_Backbone54_k2` winner (the
   experiment's two-regime model, developed from the single-regime 54-feature
   global model; falls back to the eval-1.1 `Clustering_V0_Full_k2` winner).

All figures are generated by the results notebook (`derived_8.4-eval-1.3.ipynb`),
which calls the ``plot_*`` functions below — no one-off scripts.
"""

