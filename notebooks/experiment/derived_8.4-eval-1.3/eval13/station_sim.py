def short_name(feature: str) -> str:
    """Compact tick label for a feature (e.g. J_bio_bio01 -> bio01)."""
    if feature in SHORT_NAMES:
        return SHORT_NAMES[feature]
    if feature.startswith("J_bio_bio"):
        return "bio" + feature[len("J_bio_bio"):]
    return feature


