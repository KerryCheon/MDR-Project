"""Generate the feature-selection 2.2 report from completed artifacts."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from artifact_state import artifact_is_complete, atomic_write_json, write_completion_marker


EXP_DIR = Path(__file__).resolve().parent
ARTIFACTS = EXP_DIR / "artifacts"
RESULTS_PATH = EXP_DIR / "RESULTS.md"
REPORT_DIR = ARTIFACTS / "report"


def _read_csv(path: Path) -> pd.DataFrame:
    if not path.is_file():
        raise FileNotFoundError(path)
    frame = pd.read_csv(path)
    if not np.isfinite(frame.select_dtypes(include="number").to_numpy()).all():
        raise ValueError(f"non-finite metric in {path}")
    return frame


def _require_completion(path: Path) -> None:
    if not artifact_is_complete(path, []):
        raise ValueError(f"incomplete experiment stage: {path}")


def load_selection_summary(artifact_set: str) -> dict:
    path = ARTIFACTS / artifact_set / "selection_summary.json"
    with open(path, encoding="utf-8") as stream:
        return json.load(stream)


def build_validation_table() -> pd.DataFrame:
    path = ARTIFACTS / "final/validation_eval/metrics_summary.csv"
    _require_completion(path.parent)
    return _read_csv(path).sort_values(["dataset", "model", "beta"])


def build_retrospective_table() -> pd.DataFrame:
    paths = {
        "final": ARTIFACTS / "final/retrospective_test_eval/metrics_summary.csv",
        "nested": ARTIFACTS / "nested/retrospective_test_eval/metrics_summary.csv",
        "crossed": ARTIFACTS / "crossed_candidates_locked_outer/retrospective_test_eval/metrics_summary.csv",
    }
    frames = []
    for label, path in paths.items():
        _require_completion(path.parent)
        frame = _read_csv(path).copy()
        frame.insert(0, "artifact_set", label)
        frames.append(frame)
    return pd.concat(frames, ignore_index=True)


def build_candidate_ceiling_table() -> pd.DataFrame:
    rows = []
    for artifact_set in ("nested", "crossed_candidates_locked_outer", "progressive_crossed_locked_outer"):
        path = ARTIFACTS / artifact_set / "candidate_diagnostics/global_candidates.csv"
        _require_completion(path.parent)
        candidates = _read_csv(path)
        for dataset, group in candidates.groupby("dataset", sort=True):
            beta_zero = group.loc[group["beta"] == 0.0]
            if beta_zero.empty:
                raise ValueError(f"missing beta=0 candidate diagnostics for {artifact_set}/{dataset}")
            outer_selected = beta_zero.sort_values(
                ["outer_R2", "outer_RMSE", "n_features", "candidate_index"],
                ascending=[False, True, True, True],
            ).iloc[0]
            ceiling = beta_zero.sort_values(
                ["retrospective_test_R2", "retrospective_test_RMSE", "n_features", "candidate_index"],
                ascending=[False, True, True, True],
            ).iloc[0]
            rows.append({
                "artifact_set": artifact_set,
                "dataset": dataset,
                "outer_selected_n_features": int(outer_selected["n_features"]),
                "outer_selected_retrospective_R2": float(outer_selected["retrospective_test_R2"]),
                "retrospective_ceiling_n_features": int(ceiling["n_features"]),
                "retrospective_ceiling_R2": float(ceiling["retrospective_test_R2"]),
            })
    return pd.DataFrame(rows).sort_values(["artifact_set", "dataset"])


def build_moe_table() -> pd.DataFrame:
    table = build_retrospective_table()
    nested = table.loc[(table["artifact_set"] == "nested") & (table["dataset"] == "derived_8.2") & (table["beta"] == 0.0)]
    names = ["2.2_global", "2.2_clustering_frozen_k2_shared_only", "2.2_clustering_dynamic_k2_shared_plus_delta", "2.2_clustering_refit_k2_shared_plus_delta"]
    result = nested.loc[nested["model"].isin(names)].copy()
    if result["model"].nunique() != len(names):
        raise ValueError("missing or duplicate nested MoE comparison rows")
    return result.sort_values("model")


def _markdown_table(frame: pd.DataFrame) -> str:
    display = frame.copy()
    for column in display.select_dtypes(include="number"):
        display[column] = display[column].map(lambda value: f"{value:.4f}" if isinstance(value, float) else str(value))
    return display.to_markdown(index=False)


def render_results_markdown() -> str:
    validation = build_validation_table()
    retrospective = build_retrospective_table()
    ceilings = build_candidate_ceiling_table()
    moe = build_moe_table()
    return "\n".join([
        "<!-- Generated by generate_results.py. Do not edit numeric tables manually. -->",
        "# Results: derived_8.2-feature-selection-2.2",
        "",
        "All 2023–2025 values below are retrospective diagnostics and are ineligible for an unbiased SOTA claim.",
        "",
        "## Development validation (2021–2022)",
        "",
        "Source: `run_eval.py`; artifact: `artifacts/final/validation_eval/metrics_summary.csv`.",
        "",
        _markdown_table(validation[["dataset", "model", "beta", "R2", "RMSE"]]),
        "",
        "## Retrospective evaluation (2023–2025)",
        "",
        "Source: `run_eval.py`; artifacts: final, nested, and crossed `retrospective_test_eval/metrics_summary.csv`.",
        "",
        _markdown_table(retrospective[["artifact_set", "dataset", "model", "beta", "R2", "RMSE"]]),
        "",
        "## Candidate diagnostics",
        "",
        "Source: `run_candidate_diagnostics.py`; each outer-selected row is chosen by outer R², lower outer RMSE, fewer features, then candidate index. Retrospective ceilings are descriptive only.",
        "",
        _markdown_table(ceilings),
        "",
        "## MoE ablation",
        "",
        "Source: `run_eval.py`; artifact: `artifacts/nested/retrospective_test_eval/metrics_summary.csv`; filter: dataset=`derived_8.2`, beta=`0.0`.",
        "",
        _markdown_table(moe[["model", "R2", "RMSE"]]),
        "",
    ])


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args(argv)
    markdown = render_results_markdown()
    RESULTS_PATH.write_text(markdown, encoding="utf-8")
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    atomic_write_json(REPORT_DIR / "report_manifest.json", {"results": str(RESULTS_PATH.relative_to(EXP_DIR))})
    write_completion_marker(REPORT_DIR, ["report_manifest.json"])


if __name__ == "__main__":
    main()
